// Security headers sent on every web response. No Content-Security-Policy is
// set here on purpose: Next.js inline bootstrap scripts need a nonce-based
// policy, which must be designed and tested separately. geolocation stays
// enabled for the same origin because attendance check-in uses GPS.
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(self)",
  },
];

/** @type {import('next').NextConfig} */
const nextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
